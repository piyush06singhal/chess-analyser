"""Label generation — versioned, reproducible, and never hand-edited.

A label is the thing the model is asked to predict, so an ambiguous label makes
every metric meaningless. Each label therefore carries: what it means, exactly
how it is derived, from which source, under which threshold policy, and under
which version. When a derivation changes, the version changes, and a dataset
built under the old version stays explicable.

Labels are generated by functions that read the *source*, never the features —
so a label cannot be contaminated by the inputs it will be predicted from.
"""

from __future__ import annotations

from pydantic import BaseModel, Field

from argus.datasets.records import IngestedGame

#: Bumped whenever a label's definition or derivation changes.
LABEL_VERSION = "6.0"

#: The three outcome classes, in a fixed order. Fixed order matters: a stored
#: model's class axis must mean the same thing forever.
OUTCOME_CLASSES: list[str] = ["white_win", "draw", "black_win"]

_RESULT_TO_CLASS = {"1-0": "white_win", "1/2-1/2": "draw", "0-1": "black_win"}


class LabelDefinition(BaseModel):
    """One label: meaning, derivation, source and version."""

    name: str
    target: str = Field(description="The quantity being predicted")
    values: list[str] = Field(default_factory=list, description="Allowed values, fixed order")
    definition: str
    derivation: str = Field(description="Function that produces the label")
    source_of_truth: str = Field(description="Where the ground truth comes from")
    unit_of_prediction: str
    threshold_policy: str | None = None
    label_version: str = LABEL_VERSION
    notes: list[str] = Field(default_factory=list)


class LabelledRecord(BaseModel):
    """A label attached to the record it belongs to."""

    game_id: str
    label_name: str
    value: str
    label_version: str = LABEL_VERSION
    #: Which game the label belongs to — kept explicit so a label can never float
    #: free of its record.
    source: str = ""


class LabelledDataset(BaseModel):
    """Labels plus the accounting of rows that could not be labelled."""

    labels: list[LabelledRecord] = Field(default_factory=list)
    unlabelled: list[str] = Field(default_factory=list, description="game_ids without a usable label")
    definition: LabelDefinition
    notes: list[str] = Field(default_factory=list)

    def as_map(self) -> dict[str, str]:
        """game_id → label value."""
        return {record.game_id: record.value for record in self.labels}

    def distribution(self) -> dict[str, int]:
        counts: dict[str, int] = {value: 0 for value in self.definition.values}
        for record in self.labels:
            counts[record.value] = counts.get(record.value, 0) + 1
        return counts

    def shares(self) -> dict[str, float]:
        """Class shares of the natural distribution — measured before any rebalancing."""
        total = len(self.labels)
        if not total:
            return {}
        return {value: round(count / total, 4) for value, count in self.distribution().items()}


GAME_OUTCOME_LABEL = LabelDefinition(
    name="game_outcome",
    target="The result of the game",
    values=list(OUTCOME_CLASSES),
    definition=(
        "The outcome of the game from White's perspective: white_win, draw or "
        "black_win. Drawn games are a class in their own right, not an error term."
    ),
    derivation="argus.datasets.labels.game_outcome_label",
    source_of_truth="The PGN Result header, cross-checked against the board by the importer",
    unit_of_prediction="one game",
    notes=[
        "Games without a recorded result are unlabelled, never guessed.",
        "Only a real recorded result is used: no result is inferred from the moves.",
    ],
)


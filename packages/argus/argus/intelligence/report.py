"""The structured Game Report.

Phase 4's deliverable: one deterministic, fully evidenced document describing
what happened in a game and why Caissa says so. Every section is built from

* engine facts already stored by the Phase 3 pipeline, and
* Caissa-derived board features (structure, activity, material, king safety),

and every derived claim carries its evidence and its ``source`` level:

``engine_fact``           measured by Stockfish
``argus_derived_feature`` measured from the board by Caissa code
``argus_interpretation``  a rule Caissa applies (loops, candidates, categories)

There is **no prose generation** and no LLM anywhere in this module. Statements
are factual templates filled with measurements, e.g. "White's largest evaluation
drop occurred after move 28 (-420cp)." — a fact, not a judgement. The final two
sections (key lessons, training recommendations) are structured,
evidence-carrying lists rather than narrative text.
"""


#!/usr/bin/env python
"""Repair stored analysis that describes a different game.

``check_data_consistency.py`` reports the contradiction; this script is the
explicit, auditable repair it deliberately does not perform. It is the only
place in the project that deletes derived analysis, and it does so only when a
stored per-move row provably disagrees with the game's own recorded move at the
same ply (SAN, UCI, or the position before the move).

What it removes for an affected game, in one transaction:

* the ``move_analyses`` rows that contradict the game's moves;
* ``critical_positions`` and ``game_reports`` for that game (both were derived
  from the contradictory rows and are regenerated by a fresh analysis);
* ``training_positions`` whose source ply is contradictory, or whose format is
  whole-game (``what_went_wrong`` / ``reconstruction``) and therefore read every
  ply. Exercises from a still-valid ply are kept.

It then resets the game to ``ready`` so a fresh analysis can run, and (with
``--reanalyze``) triggers that analysis through the live API.

Dry-run by default: it prints exactly what it would delete and changes nothing
until ``--apply`` is passed.

Usage:
    python scripts/repair_stale_analysis.py --database-url URL
    python scripts/repair_stale_analysis.py --database-url URL --apply
    python scripts/repair_stale_analysis.py --database-url URL --apply --reanalyze --base-url http://127.0.0.1:8002
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.request
from collections import defaultdict

WHOLE_GAME_FORMATS = ("what_went_wrong", "reconstruction")


def find_contradictions(connection) -> tuple[dict[str, dict[int, list[str]]], dict[str, set[int]]]:
    """Return {game_id: {ply: [mismatches]}} and {game_id: {affected_plies}}."""
    from sqlalchemy import text

    moves: dict[str, dict[int, tuple[str, str, str]]] = defaultdict(dict)
    for row in connection.execute(text("select game_id, ply, san, uci, fen_before from game_moves")):
        moves[row.game_id][int(row.ply)] = (row.san, row.uci, row.fen_before)

    contradictions: dict[str, dict[int, list[str]]] = defaultdict(dict)
    for row in connection.execute(
        text(
            "select game_id, ply, played_move_san, played_move_uci, fen_before "
            "from move_analyses order by game_id, ply"
        )
    ):
        published = moves.get(row.game_id, {}).get(int(row.ply))
        if published is None:
            continue
        san, uci, fen_before = published
        mismatches = []
        if row.played_move_uci != uci:
            mismatches.append(f"uci stored={uci} analysed={row.played_move_uci}")
        if (row.played_move_san or "").rstrip("?!#+") != (san or "").rstrip("?!#+"):
            mismatches.append(f"san stored={san} analysed={row.played_move_san}")
        if row.fen_before != fen_before:
            mismatches.append("fen_before differs")
        if mismatches:
            contradictions[row.game_id][int(row.ply)] = mismatches

    affected = {game_id: set(plies) for game_id, plies in contradictions.items()}
    return contradictions, affected


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--database-url", default=os.environ.get("ARGUS_DATABASE_URL", ""))
    parser.add_argument("--apply", action="store_true", help="actually perform the repair")
    parser.add_argument("--reanalyze", action="store_true", help="re-run analysis via the API after repair")
    parser.add_argument("--base-url", default="http://127.0.0.1:8002")
    args = parser.parse_args()

    url = args.database_url.strip()
    if not url:
        print("No database URL. Pass --database-url or set ARGUS_DATABASE_URL.")
        return 2

    from sqlalchemy import create_engine, text

    engine = create_engine(url, future=True)
    with engine.begin() as connection:
        contradictions, affected = find_contradictions(connection)
        if not contradictions:
            print("Nothing to repair — every stored analysis describes its game.")
            return 0

        print("Caissa STALE-ANALYSIS REPAIR")
        print("=" * 62)
        for game_id, plies in sorted(contradictions.items()):
            print(f"game {game_id}: {len(plies)} contradictory ply/plies {sorted(plies)}")

        # What else will be removed, computed before anything is deleted.
        plans = {}
        for game_id, plies in affected.items():
            ply_list = sorted(plies)
            rows = list(
                connection.execute(
                    text(
                        "select id, source_ply, position_type from training_positions "
                        "where source_game_id = :gid"
                    ),
                    {"gid": game_id},
                )
            )
            doomed_positions = [
                row.id
                for row in rows
                if (row.source_ply is not None and int(row.source_ply) in plies)
                or row.position_type in WHOLE_GAME_FORMATS
            ]
            reports = connection.execute(
                text("select count(*) from game_reports where game_id = :gid"), {"gid": game_id}
            ).scalar_one()
            criticals = connection.execute(
                text("select count(*) from critical_positions where game_id = :gid"), {"gid": game_id}
            ).scalar_one()
            plans[game_id] = {
                "plies": ply_list,
                "training_positions": doomed_positions,
                "reports": reports,
                "critical_positions": criticals,
            }
            print(
                f"  → will delete {len(ply_list)} analysis row(s), {criticals} critical position(s), "
                f"{reports} report(s), {len(doomed_positions)} training exercise(s)"
            )

        if not args.apply:
            print("\nDRY RUN — nothing was modified. Re-run with --apply to perform the repair.")
            return 0

        for game_id, plan in plans.items():
            connection.execute(
                text(
                    "delete from move_analyses where game_id = :gid and ply = any(:plies)"
                ),
                {"gid": game_id, "plies": plan["plies"]},
            )
            connection.execute(text("delete from critical_positions where game_id = :gid"), {"gid": game_id})
            connection.execute(text("delete from game_reports where game_id = :gid"), {"gid": game_id})
            if plan["training_positions"]:
                connection.execute(
                    text("delete from training_positions where id = any(:ids)"),
                    {"ids": plan["training_positions"]},
                )
            # Reset the lifecycle so a fresh, correct analysis can run.
            connection.execute(
                text(
                    "update games set analysis_status = 'ready', analysis_error = null, "
                    "analysis_updated_at = null where id = :gid"
                ),
                {"gid": game_id},
            )
            print(f"repaired {game_id}")

    if args.reanalyze:
        for game_id in sorted(affected):
            request = urllib.request.Request(
                f"{args.base_url}/api/games/{game_id}/analyze", data=b"", method="POST"
            )
            request.add_header("Content-Type", "application/json")
            try:
                with urllib.request.urlopen(request, timeout=60) as response:
                    body = json.loads(response.read().decode())
                print(
                    f"queued analysis for {game_id}: status={body.get('analysis_status')} "
                    f"depth={body.get('depth')} multipv={body.get('multipv')}"
                )
            except Exception as exc:  # noqa: BLE001 - report, do not crash the repair
                print(f"could not queue analysis for {game_id}: {exc}")

    print("\nRepair complete. Re-run check_data_consistency.py to confirm.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

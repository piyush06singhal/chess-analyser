LABEL_REGISTRY: dict[str, LabelDefinition] = {
    definition.name: definition
    for definition in (
        GAME_OUTCOME_LABEL,
        POSITION_OUTCOME_LABEL,
        POSITION_DIFFICULTY_LABEL,
        MOVE_ERROR_LABEL,
        PLAYER_PERFORMANCE_LABEL,
    )
}


def game_outcome_label(record: IngestedGame) -> str | None:
    """Outcome class for a game, or ``None`` when no result was recorded."""
    return _RESULT_TO_CLASS.get(record.result)


def position_outcome_label(record: IngestedGame) -> str | None:
    """Outcome class of the game a position belongs to."""
    return _RESULT_TO_CLASS.get(record.result)


def position_difficulty_label(
    evaluations_cp: list[int],
    *,
    in_check: bool = False,
    hanging_material: bool = False,
    volatility_threshold_cp: int = 150,
    lookahead_plies: int = 4,
) -> str | None:
    """Classify a position as difficult or ordinary from real evaluations.

    Returns ``None`` (unlabelled) when there is no evaluation to judge from —
    a heuristic stand-in would be a fabricated label.
    """
    if not evaluations_cp:
        return None
    window = evaluations_cp[: lookahead_plies + 1]
    if len(window) < 2:
        return None
    swing = max(window) - min(window)
    if swing >= volatility_threshold_cp or in_check or hanging_material:
        return "difficult"
    return "ordinary"


def move_error_label(classification: str | None) -> str | None:
    """Map a Caissa move classification onto the move-error label values."""
    if not classification:
        return None
    normalized = classification.strip().casefold()
    if normalized in {"blunder", "mistake", "inaccurate"}:
        return normalized
    if normalized in {"best", "excellent", "good", "book", "brilliant", "great", "okay"}:
        return "acceptable"
    return None


def player_performance_label(
    future_average_cpl: float | None,
) -> str | None:
    """The future-window performance value, or ``None`` when unavailable."""
    if future_average_cpl is None:
        return None
    return f"future_average_cpl={round(future_average_cpl, 4)}"


def label_games(
    records: list[IngestedGame], definition: LabelDefinition | None = None
) -> LabelledDataset:
    """Label a batch of games with the game-outcome label.

    Unlabelled games are named, not dropped: the count is a property of the
    corpus and must be visible in every downstream report.
    """
    effective = definition or GAME_OUTCOME_LABEL
    labels: list[LabelledRecord] = []
    unlabelled: list[str] = []
    for record in records:
        value = game_outcome_label(record)
        if value is None:
            unlabelled.append(record.game_id)
            continue
        labels.append(
            LabelledRecord(
                game_id=record.game_id,
                label_name=effective.name,
                value=value,
                label_version=effective.label_version,
                source=record.source,
            )
        )
    return LabelledDataset(
        labels=labels,
        unlabelled=unlabelled,
        definition=effective,
        notes=[
            f"Label version {effective.label_version}; derivation "
            f"{effective.derivation}.",
        ],
    )


